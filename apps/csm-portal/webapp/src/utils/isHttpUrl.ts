/**
 * True only for absolute http(s) URLs. Use before rendering a system- or
 * backend-supplied string as an anchor `href` (e.g. a git reference or an
 * external issue link) to reject `javascript:`/`data:`/other schemes that
 * would execute or misrepresent content when clicked.
 */
export function isHttpUrl(value: string): boolean {
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}

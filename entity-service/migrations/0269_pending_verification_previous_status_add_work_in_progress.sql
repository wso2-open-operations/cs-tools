-- Kept in its own transaction, same as 0108_case_cause_add_user_mistake.sql:
-- ALTER TYPE ... ADD VALUE can't run in the same transaction as a statement
-- that uses the new value.
--
-- The CSM portal backend (apps/csm-portal/backend) sends addedReason
-- AUTO_CLOSED for every case it closes, with previousStatus set to the
-- case's actual prior state -- but its own state machine
-- (internal/handler/state.go) only ever reaches "closed" from
-- "work_in_progress" or "solution_proposed". SOLUTION_PROPOSED already
-- existed on this enum; WORK_IN_PROGRESS did not, so a close from that
-- (the common) prior state had no legal previousStatus to send and had to
-- fall back to addedReason MANUAL instead, with the real prior state folded
-- into the note text rather than recorded in this column. Adding it here
-- lets every CSM-portal close record AUTO_CLOSED with its real previous
-- state, matching entity-service's own chk_previous_status_matches_reason
-- constraint.
ALTER TYPE pending_verification_previous_status_enum ADD VALUE IF NOT EXISTS 'WORK_IN_PROGRESS';

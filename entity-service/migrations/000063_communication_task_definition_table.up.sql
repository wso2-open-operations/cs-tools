-- Standalone entity table (own id/audit columns), same shape as
-- communication_plan (000062_communication_plan_table.up.sql).
-- "order" is a reserved word - quoted here.
CREATE TABLE IF NOT EXISTS communication_task_definition (
    id UUID PRIMARY KEY,
    created_on TIMESTAMPTZ NOT NULL,
    updated_on TIMESTAMPTZ NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    name VARCHAR(255),
    description TEXT,
    "order" INTEGER
);
